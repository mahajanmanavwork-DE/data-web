#!/usr/bin/env python3
import argparse, sys, os, json, urllib.request, subprocess, time
BASE = os.path.dirname(os.path.abspath(__file__))
PIDFILE = os.path.join(BASE, "dataweb.pid")
DOWNLOADS = [("https://example.com/file1.csv","input_files/file1.csv"),("https://example.com/file2.csv","input_files/file2.csv")]

def _find_cloudflared():
    """Find cloudflared binary in system PATH, project dir, or desktop."""
    binary_name = "cloudflared.exe" if sys.platform == "win32" else "cloudflared"
    # 1. Check system PATH first
    for path_dir in os.environ.get("PATH", "").split(os.pathsep):
        candidate = os.path.join(path_dir, binary_name)
        if os.path.exists(candidate) and os.access(candidate, os.X_OK):
            return candidate
    # 2. Check project directory
    project_binary = os.path.join(BASE, binary_name)
    if os.path.exists(project_binary):
        return project_binary
    # 3. Check desktop copy
    desktop_binary = os.path.join(os.path.expanduser("~"), "Desktop", "college-prac-2", binary_name)
    if os.path.exists(desktop_binary):
        return desktop_binary
    return None


def cmd_setup():
    if sys.version_info < (3,10): sys.exit(1)
    for d in ["input_files","output_files","storage","env","metadata"]:
        os.makedirs(os.path.join(BASE,d), exist_ok=True)
    
    # Generate secure secret key
    import secrets
    secret_key = secrets.token_urlsafe(32)
    
    # Write complete .env with all required variables
    env_path = os.path.join(BASE,"env",".env")
    env_content = f"""# DataWeb Environment Configuration
# Generated by 'dataweb setup' on {time.strftime('%Y-%m-%d %H:%M:%S')}

# Folder paths (relative to project root)
input_folder=input_files
output_folder=output_files
storage_folder=storage
metadata_path=storage/metadata.json
df_registry_path=storage/registry.json
operations_path=storage/operations.json
current_df_key_path=storage/current_key.json
users_path=storage/users.json

# Security (CHANGE IN PRODUCTION)
secret_key={secret_key}
"""
    if not os.path.exists(env_path):
        open(env_path,"w").write(env_content)
        print(f"Created {env_path} with generated secret_key")
    else:
        print(f"{env_path} already exists, skipping")
    
    # Create users.json with bcrypt-hashed admin password
    users_path = os.path.join(BASE,"storage","users.json")
    if not os.path.exists(users_path):
        import bcrypt
        admin_hash = bcrypt.hashpw(b"admin", bcrypt.gensalt()).decode()
        open(users_path,"w").write(json.dumps({"admin":{"password":admin_hash,"current_key":None,"selected_file":None,"operations":{}}}, indent=4))
        print(f"Created {users_path} with hashed admin password")
    else:
        print(f"{users_path} already exists, skipping")
    
    # Ensure venv and dependencies installed FIRST
    venv_dir = os.path.join(BASE, ".venv")
    if not os.path.exists(venv_dir):
        print("Creating .venv...")
        subprocess.run([sys.executable, "-m", "venv", venv_dir], check=False)
    if sys.platform == "win32":
        venv_python = os.path.join(venv_dir, "Scripts", "python.exe")
    else:
        venv_python = os.path.join(venv_dir, "bin", "python")
    # Activate venv environment variables
    if sys.platform == "win32":
        venv_bin = os.path.join(venv_dir, "Scripts")
    else:
        venv_bin = os.path.join(venv_dir, "bin")
    activated_env = {**os.environ, "VIRTUAL_ENV": venv_dir, "PATH": venv_bin + os.pathsep + os.environ.get("PATH", "")}
    if not os.path.exists(venv_python):
        venv_python = sys.executable
    print("Activated .venv at:", venv_dir)
    print("Installing dependencies in venv using:", venv_python)
    for cmd_args in [
        [venv_python, "-m", "pip", "install", "--upgrade", "pip"],
        [venv_python, "-m", "pip", "install", "-e", BASE],
    ]:
        try:
            subprocess.run(cmd_args, env=activated_env, check=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        except Exception as e:
            print(f"Install step failed: {e}")
    req_path = os.path.join(BASE, "requirements.txt")
    if os.path.exists(req_path):
        try:
            subprocess.run([venv_python, "-m", "pip", "install", "-r", req_path], env=activated_env, check=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            print("Installed requirements.txt in venv.")
        except Exception as e:
            print(f"Requirements install failed: {e}")
    # Downloads after venv/dependency setup
    for url,dest in DOWNLOADS:
        target = os.path.join(BASE,dest)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        try: urllib.request.urlretrieve(url, target)
        except Exception as e: print(f"Download fail: {e}")
    print("dataweb setup complete (venv ready).")
    # Copy cloudflared to project if found in system PATH but not in project
    binary_name = "cloudflared.exe" if sys.platform == "win32" else "cloudflared"
    binary_path = os.path.join(BASE, binary_name)
    if not os.path.exists(binary_path):
        system_cf = _find_cloudflared()
        if system_cf and system_cf != binary_path:
            import shutil
            shutil.copy(system_cf, binary_path)
            print(f"Copied cloudflared from {system_cf} to project.")
        else:
            print("cloudflared binary not found in system PATH. Download it manually or run from project folder.")

def cmd_run(silent=False):
    import sys as s; s.path.insert(0, BASE)
    log_level = "warning" if silent else "info"
    stdout_dest = subprocess.DEVNULL if silent else None
    stderr_dest = subprocess.DEVNULL if silent else None
# Use project's .venv explicitly (sys.executable points to Hermes runtime venv which lacks packages)
    if sys.platform == "win32":
        venv_python_path = os.path.join(BASE, ".venv", "Scripts", "python.exe")
        if not os.path.exists(venv_python_path):
            venv_python_path = sys.executable
    else:
        venv_python_path = os.path.join(BASE, ".venv", "bin", "python")
        if not os.path.exists(venv_python_path):
            venv_python_path = sys.executable
    python_for_uvicorn = venv_python_path
    proc = subprocess.Popen(
        [python_for_uvicorn, "-m", "uvicorn", "main:app", "--host", "0.0.0.0", "--port", "5000", "--log-level", log_level],
        stdout=open(os.path.join(BASE,"uvicorn_stdout.log"),"w"),
        stderr=open(os.path.join(BASE,"uvicorn_stdout.log"),"w"),
        stdin=subprocess.DEVNULL,
        start_new_session=True,
        cwd=BASE,
        env={**os.environ, "PYTHONPATH": BASE + ":" + os.environ.get("PYTHONPATH", "")}
    )
    with open(PIDFILE, "w") as f:
        f.write(str(proc.pid))
    print("Server started (PID", proc.pid, ")" + (" silent" if silent else ""))
    try:
        tunnel_log = os.path.join(BASE, "tunnel.log")
        cf_binary = _find_cloudflared()
        if not cf_binary:
            print("cloudflared binary not found. Run 'dataweb setup' or install cloudflared.")
            return
        with open(tunnel_log, "w") as logf:
            tunnel = subprocess.Popen(
                [cf_binary, "tunnel", "--url", "http://localhost:5000"],
                stdout=logf, stderr=logf, stdin=subprocess.DEVNULL,
                start_new_session=True, cwd=BASE
            )
        import time
        for _ in range(30):
            time.sleep(0.5)
            if not os.path.exists(tunnel_log):
                continue
            with open(tunnel_log, "r") as f:
                content = f.read()
            for line in content.splitlines():
                if "trycloudflare.com" in line:
                    for part in line.split():
                        if part.startswith("https://") and "trycloudflare.com" in part:
                            print("Public URL:", part)
                            url_path = os.path.join(BASE, "tunnel_url.txt")
                            open(url_path, "w").write(part)
                            storage_dir = os.path.join(BASE, "storage")
                            os.makedirs(storage_dir, exist_ok=True)
                            history_path = os.path.join(storage_dir, "tunnel_history.log")
                            import time
                            with open(history_path, "a") as h:
                                h.write(f"{time.strftime('%Y-%m-%d %H:%M:%S')} | {part}\n")
                            if os.path.exists(tunnel_log):
                                with open(tunnel_log, "r") as src, open(history_path, "a") as dst:
                                    dst.write(src.read() + "\n---\n")
                            return
        # Final check: read tunnel.log once and save any URL found
        url_path = os.path.join(BASE, "tunnel_url.txt")
        found_url = None
        if os.path.exists(tunnel_log):
            with open(tunnel_log, "r") as f:
                for line in f.read().splitlines():
                    if "trycloudflare.com" in line:
                        for part in line.split():
                            if part.startswith("https://") and "trycloudflare.com" in part:
                                found_url = part
        if found_url:
            open(url_path, "w").write(found_url)
            print("Public URL (saved to tunnel_url.txt):", found_url)
            storage_dir = os.path.join(BASE, "storage")
            os.makedirs(storage_dir, exist_ok=True)
            history_path = os.path.join(storage_dir, "tunnel_history.log")
            import time
            with open(history_path, "a") as h:
                h.write(f"{time.strftime('%Y-%m-%d %H:%M:%S')} | {found_url}\n")
            return
        else:
            print("Tunnel running but URL not yet visible in terminal.")
            print("Check", tunnel_log, "or", url_path, "for the trycloudflare.com link.")
    except Exception as e:
        print("Tunnel error (cloudflared):", e)

def _find_pid_on_port(port=5000):
    if sys.platform == "win32":
        try:
            out = subprocess.check_output(["netstat", "-ano"], text=True)
            for line in out.splitlines():
                if f":{port}" in line and "LISTENING" in line:
                    parts = line.split()
                    return int(parts[-1])
        except Exception:
            pass
    else:
        try:
            out = subprocess.check_output(["ss", "-tlnp"], text=True, stderr=subprocess.STDOUT)
            for line in out.splitlines():
                if f":{port}" in line:
                    import re
                    m = re.search(r"pid=(\d+)", line)
                    if m:
                        return int(m.group(1))
        except Exception:
            pass
    return None

def cmd_stop():
    pid = _find_pid_on_port(5000)
    if pid is None:
        if os.path.exists(PIDFILE):
            try:
                pid = int(open(PIDFILE).read())
            except Exception:
                pass
    if pid:
        try:
            if sys.platform == "win32":
                subprocess.run(["taskkill", "/F", "/PID", str(pid), "/T"], capture_output=True)
            else:
                try:
                    os.kill(pid, 9)
                except ProcessLookupError:
                    pass
            print("Server stopped.")
        except Exception as e:
            print(f"Stop error: {e}")
    else:
        print("Server not running (port 5000 not found).")
    if os.path.exists(PIDFILE):
        try:
            os.remove(PIDFILE)
        except Exception:
            pass
    url_file = os.path.join(BASE, "tunnel_url.txt")
    for temp in [url_file, os.path.join(BASE, "tunnel.log"), os.path.join(BASE, "uvicorn_stdout.log")]:
        if os.path.exists(temp):
            try:
                os.remove(temp)
            except Exception:
                pass

def cmd_users():
    users_path = os.path.join(BASE, "storage", "users.json")
    if not os.path.exists(users_path):
        print("No users file.")
        return
    users = json.load(open(users_path))
    print(f"Total users: {len(users)}")
    for name in users:
        print(f" - {name}")

def cmd_user_add(name, pw):
    users_path = os.path.join(BASE, "storage", "users.json")
    users = {}
    if os.path.exists(users_path):
        users = json.load(open(users_path))
    if name in users:
        print("User exists")
        return
    import bcrypt
    hashed = bcrypt.hashpw(pw.encode(), bcrypt.gensalt()).decode()
    users[name] = {"password": hashed, "current_key": None, "selected_file": None, "operations": {}}
    open(users_path, "w").write(json.dumps(users, indent=4))
    print("User added")

def cmd_start():
    # Check if anything is listening on port 5000 (cross-platform)
    try:
        import socket
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.settimeout(1)
        result = s.connect_ex(("127.0.0.1", 5000))
        s.close()
        if result == 0:
            print("running")
            return
    except Exception:
        pass
    print("stopped")

def main():
    p = argparse.ArgumentParser(prog="dataweb")
    p.add_argument("command", choices=["setup","run","stop","users","user","start","status"])
    p.add_argument("--name", default=None)
    p.add_argument("--password", default=None)
    p.add_argument("--silent", action="store_true")
    args = p.parse_args()
    if args.command == "setup": cmd_setup()
    elif args.command == "run": cmd_run(silent=args.silent)
    elif args.command == "users": cmd_users()
    elif args.command == "user":
        if args.name and args.password:
            cmd_user_add(args.name, args.password)
        else:
            print("Usage: dataweb user --name NAME --password PASS")
    elif args.command == "start" or args.command == "status": cmd_start()
    elif args.command == "stop": cmd_stop()
if __name__ == "__main__":
    main()
